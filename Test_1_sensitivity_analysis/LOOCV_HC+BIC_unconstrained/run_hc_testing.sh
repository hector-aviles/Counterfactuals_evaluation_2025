#!/usr/bin/env bash
# =============================================================================
# run_hc_testing.sh
#
# Runs counterfactual testing for all 7 HC+BIC sensitivity combinations.
# Each combination is called independently — safe to rerun any one of them.
#
# Usage:
#   chmod +x run_hc_testing.sh
#   ./run_hc_testing.sh [--folds START-END] 2>&1 | tee hc_testing_master.log
#
# To resume a specific combination from fold 10:
#   python3 run_hc_testing.py ./hc_bic_restart0_perturb1_maxpInf_fracp25 --folds 10-78
# =============================================================================

set -euo pipefail

FOLDS="1-78"

# Parse optional --folds argument
while [[ $# -gt 0 ]]; do
  case "$1" in
    --folds) FOLDS="$2"; shift 2 ;;
    *) echo "Unknown argument: $1"; exit 1 ;;
  esac
done

SCRIPT="run_hc_testing.py"

if [ ! -f "$SCRIPT" ]; then
  echo "ERROR: $SCRIPT not found in $(pwd)"
  exit 1
fi

run_combo() {
  local combo_dir="$1"
  if [ ! -d "$combo_dir" ]; then
    echo "[Warning] Directory not found: $combo_dir — skipping"
    return
  fi
  echo ""
  echo "========================================================"
  echo "  Testing combination: $(basename $combo_dir)"
  echo "  Folds: $FOLDS"
  echo "  $(date)"
  echo "========================================================"
  python3 "$SCRIPT" "$combo_dir" --folds "$FOLDS"
  echo "  Finished: $(basename $combo_dir)  ($(date))"
}

# Run all 7 combinations — must match labels generated by CBNs_HC_sensitivity.R
run_combo "./hc_bic_restart0_perturb1_maxpInf_fracp25"
run_combo "./hc_bic_restart5_perturb1_maxpInf_fracp25"
run_combo "./hc_bic_restart10_perturb1_maxpInf_fracp25"
run_combo "./hc_bic_restart0_perturb1_maxp3_fracp25"
run_combo "./hc_bic_restart0_perturb1_maxp5_fracp25"
run_combo "./hc_bic_restart0_perturb2_maxpInf_fracp25"
run_combo "./hc_aic_restart0_perturb1_maxpInf_fracp25"

echo ""
echo "========================================================"
echo "  All testing completed: $(date)"
echo "  Aggregate results in each combo dir:"
echo "    ./<combo>/twin_networks_results_all.csv"
echo "========================================================"
